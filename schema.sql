create table if not exists public.t0_diario (
    id bigint generated by default as identity primary key,
    data date not null,
    codigo_base text not null,
    base text not null,
    regional text,
    uf text,
    rm text,
    sc text,
    total_pedidos integer not null default 0,
    t0_ok integer not null default 0,
    t0_perdido integer not null default 0,
    taxa_t0 numeric(7,4) not null default 0,
    atualizado_em timestamptz not null default now(),
    constraint t0_diario_data_codigo_key unique (data, codigo_base)
);

create index if not exists idx_t0_diario_data on public.t0_diario(data);
create index if not exists idx_t0_diario_rm on public.t0_diario(rm);
create index if not exists idx_t0_diario_sc on public.t0_diario(sc);
create index if not exists idx_t0_diario_uf on public.t0_diario(uf);
create index if not exists idx_t0_diario_base on public.t0_diario(base);
